"""Generates static DEFAULT_ARCHETYPE_REGISTRY from consensus YAML matrix.

Reads architecture/designs/matrix/archetype_taxonomy_v0.2.1.yaml, validates
against installed ed-models AST, and emits:
src/ed_resolver/core/domain/classification/registry.py
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path
from typing import Any

# Ensure project root is in sys.path
_PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

import yaml  # noqa: E402

from scripts.inspect_ed_models_taxonomy import (  # noqa: E402
    DiscoveredDomain,
    crawl_ed_models_taxonomy,
)

DEFAULT_MATRIX_PATH = Path("architecture/designs/matrix/archetype_taxonomy_v0.2.1.yaml")
DEFAULT_TARGET_PATH = Path("src/ed_resolver/core/domain/classification/registry.py")


def load_taxonomy_matrix(matrix_path: Path) -> dict[str, Any]:
    """Load and parse the structured YAML taxonomy matrix."""
    if not matrix_path.is_file():
        raise FileNotFoundError(f"Matrix file not found: {matrix_path}")
    data: dict[str, Any] = yaml.safe_load(matrix_path.read_text(encoding="utf-8"))
    if "categories" not in data:
        raise ValueError(f"Matrix YAML missing required 'categories' key: {matrix_path}")
    return data


def validate_matrix_against_models(
    matrix_data: dict[str, Any], domains: list[DiscoveredDomain]
) -> None:
    """Validate 100% reconciliation between matrix YAML and ed-models AST."""
    categories = matrix_data["categories"]
    missing_in_matrix: list[str] = []

    for d in domains:
        if d.category not in categories:
            missing_in_matrix.append(f"Category: {d.category}")
            continue

        cat_models = categories[d.category].get("models", {})
        for m in d.models:
            if m.name not in cat_models:
                missing_in_matrix.append(f"{d.category}.{m.name}")

    if missing_in_matrix:
        msg = (
            f"Discrepancy Gate Failed: {len(missing_in_matrix)} models missing from matrix:\n"
            + "\n".join(missing_in_matrix)
        )
        raise ValueError(msg)


def generate_registry_source(matrix_data: dict[str, Any], domains: list[DiscoveredDomain]) -> str:
    """Synthesize type-hinted Python source code for registry.py."""
    lines: list[str] = [
        '"""Autogenerated default archetype taxonomy registry.',
        "",
        "Generated by scripts/generate_archetype_registry.py from:",
        "architecture/designs/matrix/archetype_taxonomy_v0.2.1.yaml",
        "",
        "DO NOT EDIT MANUALLY.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from types import MappingProxyType",
        "from typing import Any, Mapping",
        "",
    ]

    # Organize imports per concrete submodule path
    categories = matrix_data["categories"]
    modules_to_classes: dict[str, set[str]] = {}
    for d in sorted(domains, key=lambda x: x.category):
        for m in d.models:
            modules_to_classes.setdefault(m.module, set()).add(m.name)

    for mod_path in sorted(modules_to_classes.keys()):
        class_names = sorted(modules_to_classes[mod_path])
        if class_names:
            formatted_classes = ", ".join(class_names)
            lines.append(f"from {mod_path} import ({formatted_classes})")

    lines.extend(
        [
            "",
            "from ed_resolver.core.domain.archetypes import TelemetryArchetype",
            "",
            "DEFAULT_ARCHETYPE_REGISTRY: Mapping[",
            "    type[Any], TelemetryArchetype",
            "] = MappingProxyType(",
            "    {",
        ]
    )

    for d in sorted(domains, key=lambda x: x.category):
        cat_models = categories.get(d.category, {}).get("models", {})
        lines.append(f"        # Domain: {d.category}")
        for m in sorted(d.models, key=lambda x: x.name):
            archetype_name = cat_models.get(m.name, {}).get("archetype", "PASSIVE")
            lines.append(f"        {m.name}: TelemetryArchetype.{archetype_name},")
        lines.append("")

    lines.extend(
        [
            "    }",
            ")",
            "",
        ]
    )

    return "\n".join(lines)


def run_generator(
    matrix_path: Path = DEFAULT_MATRIX_PATH,
    target_path: Path = DEFAULT_TARGET_PATH,
    check_only: bool = False,
) -> int:
    """Execute generator pipeline."""
    try:
        matrix_data = load_taxonomy_matrix(matrix_path)
        domains = crawl_ed_models_taxonomy()
        validate_matrix_against_models(matrix_data, domains)
        source_code = generate_registry_source(matrix_data, domains)

        if check_only:
            if not target_path.is_file():
                print(f"Check Failed: Target file {target_path} does not exist.")
                return 1
            existing = target_path.read_text(encoding="utf-8")
            if existing.strip() != source_code.strip():
                print(f"Check Failed: {target_path} drifts from consensus matrix.")
                return 1
            print(f"Check Passed: {target_path} matches consensus matrix.")
            return 0

        target_path.parent.mkdir(parents=True, exist_ok=True)
        target_path.write_text(source_code, encoding="utf-8")

        # Format generated file with ruff
        subprocess.run(["uv", "run", "ruff", "format", str(target_path)], check=True)
        subprocess.run(["uv", "run", "ruff", "check", "--fix", str(target_path)], check=True)

        total_models = sum(len(d.models) for d in domains)
        print(f"Successfully generated {target_path} ({total_models} models mapped).")
        return 0

    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


def main() -> None:
    """Main CLI entrypoint."""
    parser = argparse.ArgumentParser(description="Generate default archetype registry from matrix.")
    parser.add_argument(
        "--matrix", type=Path, default=DEFAULT_MATRIX_PATH, help="Taxonomy matrix YAML"
    )
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_TARGET_PATH, help="Target registry.py file"
    )
    parser.add_argument(
        "--check", action="store_true", help="Verification mode: check without writing"
    )
    args = parser.parse_args()

    sys.exit(run_generator(matrix_path=args.matrix, target_path=args.output, check_only=args.check))


if __name__ == "__main__":
    main()
